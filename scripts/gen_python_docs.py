"""Write the generated parts of docs/python.md from the Python package's tables.

    scripts/gen_python_docs.py           rewrite the generated sections
    scripts/gen_python_docs.py --check   exit 1 if a section differs (CI, check.sh)

Each section sits between the markers ``<!-- NAME: generated by scripts/gen_python_docs.py -->``
and ``<!-- end NAME -->``: ``keywords``, the keyword reference
(``axtb._keywords.markdown_table()``), and ``accuracy``, the fitted constants of the accuracy
model (``axtb._accuracy.CALIBRATION``, written by tests/accuracy_calibration.py). Needs the axtb
package (a wheel or ``maturin develop``) importable.
"""
import argparse
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
DOC = ROOT / "docs/python.md"
SECTIONS = {
    name: (f"<!-- {name}: generated by scripts/gen_python_docs.py -->", f"<!-- end {name} -->")
    for name in ("keywords", "accuracy")
}


def accuracy_tables() -> str:
    """The calibration's constants as Markdown tables."""
    from axtb import _accuracy

    c = _accuracy.CALIBRATION
    out = [
        "Envelopes err <= k acc^p of the energy (Eh) and the gradient's largest component (Eh/bohr), per "
        "method, conventions kind (`axtb`, or `program`: the reference program's) and shell:",
        "",
        "| fit | energy k | energy p | gradient k | gradient p |",
        "|---|---|---|---|---|",
    ]
    for key, f in c["scf"].items():
        e, g = f["energy"], f["gradient"]
        out.append(f"| {key} | {e['k']:g} | {e['p']:g} | {g['k']:g} | {g['p']:g} |")
    tables = c.get("tables", {})
    if tables:
        names = list(tables)
        out += ["", "Tables (no envelope fits): the largest error measured at each factor.", ""]
        out.append("| acc | " + " | ".join(f"{n} energy | {n} gradient" for n in names) + " |")
        out.append("|---" * (1 + 2 * len(names)) + "|")
        for i, row in enumerate(tables[names[0]]["energy"]):
            cells = [f"{row[0]:g}"]
            for n in names:
                cells += [f"{tables[n]['energy'][i][1]:g}", f"{tables[n]['gradient'][i][1]:g}"]
            out.append("| " + " | ".join(cells) + " |")
    out += [
        "",
        "Hessians: err <= k h^p (Eh/bohr², the largest element) at `hessian.accuracy_scale` h:",
        "",
        "| method and Hessian method | k | p |",
        "|---|---|---|",
    ]
    for key, f in c["hessian"].items():
        out.append(f"| {key} | {f['k']:g} | {f['p']:g} |")
    accs = ", ".join(f"{a:g}" for a in c["accs"])
    haccs = ", ".join(f"{a:g}" for a in c["hessian_accs"])
    out += [
        "",
        f"Factors measured: {accs} (SCF), {haccs} (Hessian). Safety factor {_accuracy.SAFETY:g}, factor "
        f"range {_accuracy.ACC_FLOOR:g} to {_accuracy.ACC_MAX:g}. Data: `{c['source']}`.",
    ]
    return "\n".join(out)


def generated():
    from axtb import _keywords

    return {"keywords": _keywords.markdown_table(), "accuracy": accuracy_tables()}


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--check", action="store_true")
    a = ap.parse_args()
    text = DOC.read_text()
    new = text
    for name, body in generated().items():
        begin, end = SECTIONS[name]
        if begin not in new or end not in new:
            sys.exit(f"{DOC}: the markers of section {name} are missing")
        head, rest = new.split(begin, 1)
        _, tail = rest.split(end, 1)
        new = f"{head}{begin}\n\n{body.strip()}\n\n{end}{tail}"
    if a.check:
        if new != text:
            sys.exit(f"{DOC} is stale: run scripts/gen_python_docs.py")
        print(f"{DOC.relative_to(ROOT)}: generated sections current")
        return
    DOC.write_text(new)
    print(f"wrote {DOC.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
