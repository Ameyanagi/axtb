"""Write the generated parts of docs/python.md from the Python package's tables.

    scripts/gen_python_docs.py           rewrite the generated sections
    scripts/gen_python_docs.py --check   exit 1 if a section differs (CI, check.sh)

The keyword reference comes from ``axtb._keywords.markdown_table()`` and sits between the
markers ``<!-- keywords: generated by scripts/gen_python_docs.py -->`` and
``<!-- end keywords -->``. Needs the axtb package (a wheel or ``maturin develop``) importable.
"""
import argparse
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
DOC = ROOT / "docs/python.md"
SECTIONS = {
    "keywords": ("<!-- keywords: generated by scripts/gen_python_docs.py -->", "<!-- end keywords -->"),
}


def generated():
    from axtb import _keywords

    return {"keywords": _keywords.markdown_table()}


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--check", action="store_true")
    a = ap.parse_args()
    text = DOC.read_text()
    new = text
    for name, body in generated().items():
        begin, end = SECTIONS[name]
        if begin not in new or end not in new:
            sys.exit(f"{DOC}: the markers of section {name} are missing")
        head, rest = new.split(begin, 1)
        _, tail = rest.split(end, 1)
        new = f"{head}{begin}\n\n{body.strip()}\n\n{end}{tail}"
    if a.check:
        if new != text:
            sys.exit(f"{DOC} is stale: run scripts/gen_python_docs.py")
        print(f"{DOC.relative_to(ROOT)}: generated sections current")
        return
    DOC.write_text(new)
    print(f"wrote {DOC.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
